package cli

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/frivas/turnsmith/internal/app"
)

var completionCommands = []string{"puzzles", "version", "help", "inspect", "inverse", "guide", "sessions", "timer", "train", "daily", "completion"}

// Flags are scoped to the command that parses them. Values are completed from
// the running binary's registry, so optional puzzle methods remain discoverable.
var completionFlags = map[string]string{
	"":        "--puzzle --method --length --count --seed --json --steps --diagram --color --color-depth --help --version",
	"puzzles": "--json --help", "version": "--help", "help": "--help",
	"inspect":    "--alg --file --stdin --index --puzzle --steps --diagram --json --color --color-depth --help",
	"inverse":    "--alg --file --stdin --index --puzzle --json --help",
	"guide":      "--alg --file --index --puzzle --seed --method --length --color --color-depth --help",
	"sessions":   "--data-dir --json --session --time --scramble --penalty --notes --id --format --file --replace --token --puzzle --method --seed --algorithm-version --help",
	"timer":      "--session --data-dir --puzzle --method --seed --length --inspection --help",
	"train":      "--file --mode --seed --data-dir --list --json --export-progress --import-progress --case --status --input --output --token --replace --color --color-depth --help",
	"daily":      "--date --name --puzzle --method --count --length --json --output --help",
	"completion": "--help",
}

func (c CLI) completionCommand(args []string, out io.Writer) error {
	if len(args) == 1 && (args[0] == "--help" || args[0] == "-h") {
		return commandHelp(out, "completion")
	}
	if len(args) != 1 {
		return app.Invalid("completion requires one shell: bash, zsh, fish, or powershell")
	}
	values := map[string]string{"color": "auto always never", "color-depth": "auto 16 256 truecolor", "inspection": "0 15", "penalty": "none +2 DNF", "format": "json csv", "mode": "balanced learning slowest sequential", "status": "new learning known"}
	var puzzles, methods []string
	if c.Service.Registry != nil {
		for _, d := range c.Service.Registry.List() {
			puzzles = append(puzzles, d.ID)
			puzzles = append(puzzles, d.Aliases...)
			for _, m := range d.Methods {
				methods = append(methods, m.ID)
			}
		}
	}
	values["puzzle"] = strings.Join(uniqueCompletion(puzzles), " ")
	values["method"] = strings.Join(uniqueCompletion(methods), " ")
	var text string
	switch args[0] {
	case "bash":
		text = bashCompletion(values)
	case "zsh":
		text = zshCompletion(values)
	case "fish":
		text = fishCompletion(values)
	case "powershell":
		text = powershellCompletion(values)
	default:
		return app.Invalid("unsupported completion shell %q; choose bash, zsh, fish, or powershell", args[0])
	}
	if _, err := io.WriteString(out, text); err != nil {
		return fmt.Errorf("write completion: %w", err)
	}
	return nil
}

func uniqueCompletion(values []string) []string {
	sort.Strings(values)
	result := []string{}
	for _, value := range values {
		if len(result) == 0 || value != result[len(result)-1] {
			result = append(result, value)
		}
	}
	return result
}
func completionKeys(values map[string]string) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
func shellQuote(text string) string { return "'" + strings.ReplaceAll(text, "'", "'\\''") + "'" }
func completionChoices(command string) string {
	flags := completionFlags[command]
	if command == "" {
		return strings.Join(completionCommands, " ") + " " + flags
	}
	if command == "sessions" {
		return "list new show add edit delete delete-session export import recover lock unlock " + flags
	}
	if command == "completion" {
		return "bash zsh fish powershell " + flags
	}
	if command == "train" {
		return "practice list status export import recover lock unlock " + flags
	}
	return flags
}

func bashCompletion(values map[string]string) string {
	var b strings.Builder
	b.WriteString("# Generated by turnsmith completion bash. Source explicitly.\n_turnsmith() {\n  local cur prev choices item\n  COMPREPLY=()\n  cur=\"${COMP_WORDS[COMP_CWORD]}\"\n  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n  case \"$prev\" in\n")
	for _, key := range completionKeys(values) {
		pattern := "--" + key
		if key == "puzzle" {
			pattern += "|-p"
		}
		fmt.Fprintf(&b, "    %s) choices=%s ;;\n", pattern, shellQuote(values[key]))
	}
	b.WriteString("    --file|--input|--output|--import-progress|--data-dir)\n      while IFS= read -r item; do COMPREPLY+=(\"$item\"); done < <(compgen -f -- \"$cur\")\n      return ;;\n    *)\n      case \"${COMP_WORDS[1]}\" in\n")
	for _, command := range completionCommands {
		fmt.Fprintf(&b, "        %s) choices=%s ;;\n", command, shellQuote(completionChoices(command)))
	}
	fmt.Fprintf(&b, "        *) choices=%s ;;\n", shellQuote(completionChoices("")))
	b.WriteString("      esac ;;\n  esac\n  while IFS= read -r item; do COMPREPLY+=(\"$item\"); done < <(compgen -W \"$choices\" -- \"$cur\")\n}\ncomplete -F _turnsmith turnsmith\n")
	return b.String()
}

func zshCompletion(values map[string]string) string {
	var b strings.Builder
	b.WriteString("#compdef turnsmith\n# Generated by turnsmith completion zsh.\n_turnsmith() {\n  local -a choices\n  local prev=${words[CURRENT-1]}\n  case $prev in\n")
	for _, key := range completionKeys(values) {
		pattern := "--" + key
		if key == "puzzle" {
			pattern += "|-p"
		}
		fmt.Fprintf(&b, "    %s) choices=(%s) ;;\n", pattern, values[key])
	}
	b.WriteString("    --file|--input|--output|--import-progress) _files; return ;;\n    --data-dir) _files -/; return ;;\n    *)\n      case ${words[2]} in\n")
	for _, command := range completionCommands {
		fmt.Fprintf(&b, "        %s) choices=(%s) ;;\n", command, completionChoices(command))
	}
	fmt.Fprintf(&b, "        *) choices=(%s) ;;\n", completionChoices(""))
	b.WriteString("      esac ;;\n  esac\n  compadd -- ${choices[@]}\n}\ncompdef _turnsmith turnsmith\n")
	return b.String()
}

func fishCompletion(values map[string]string) string {
	var b strings.Builder
	b.WriteString("# Generated by turnsmith completion fish.\ncomplete -c turnsmith -f\n")
	fmt.Fprintf(&b, "complete -c turnsmith -n '__fish_use_subcommand' -a %s\n", shellQuote(strings.Join(completionCommands, " ")))
	boolean := map[string]bool{"json": true, "steps": true, "diagram": true, "help": true, "version": true, "stdin": true, "replace": true, "list": true, "export-progress": true}
	for _, command := range completionKeys(completionFlags) {
		condition := "__fish_use_subcommand"
		if command != "" {
			condition = "__fish_seen_subcommand_from " + command
		}
		if command == "sessions" {
			fmt.Fprintf(&b, "complete -c turnsmith -n %s -a 'list new show add edit delete delete-session export import recover lock unlock'\n", shellQuote(condition))
		}
		if command == "completion" {
			fmt.Fprintf(&b, "complete -c turnsmith -n %s -a 'bash zsh fish powershell'\n", shellQuote(condition))
		}
		if command == "train" {
			fmt.Fprintf(&b, "complete -c turnsmith -n %s -a 'practice list status export import recover lock unlock'\n", shellQuote(condition))
		}
		for _, flag := range strings.Fields(completionFlags[command]) {
			key := strings.TrimPrefix(flag, "--")
			fmt.Fprintf(&b, "complete -c turnsmith -n %s -l %s", shellQuote(condition), key)
			if key == "puzzle" {
				b.WriteString(" -s p")
			}
			if key == "count" {
				b.WriteString(" -s n")
			}
			if key == "length" {
				b.WriteString(" -s l")
			}
			if key == "help" {
				b.WriteString(" -s h")
			}
			if !boolean[key] {
				b.WriteString(" -r")
			}
			if key == "file" || key == "input" || key == "output" || key == "data-dir" || key == "import-progress" {
				b.WriteString(" -F")
			}
			if choices, ok := values[key]; ok {
				fmt.Fprintf(&b, " -a %s", shellQuote(choices))
			}
			b.WriteByte('\n')
		}
	}
	return b.String()
}

func powershellCompletion(values map[string]string) string {
	quote := func(text string) string { return "'" + strings.ReplaceAll(text, "'", "''") + "'" }
	array := func(text string) string {
		parts := strings.Fields(text)
		for i := range parts {
			parts[i] = quote(parts[i])
		}
		return "@(" + strings.Join(parts, ",") + ")"
	}
	var b strings.Builder
	b.WriteString("# Generated by turnsmith completion powershell. Dot-source explicitly.\nRegister-ArgumentCompleter -Native -CommandName turnsmith -ScriptBlock {\n  param($wordToComplete, $commandAst, $cursorPosition)\n  $parts = @($commandAst.CommandElements | Where-Object { $_.Extent.StartOffset -lt $cursorPosition } | ForEach-Object { $_.Extent.Text })\n  $previous = if ($parts.Count -gt 1) { $parts[-1] } else { '' }\n  if ($wordToComplete -and $previous -eq $wordToComplete) { $previous = if ($parts.Count -gt 2) { $parts[-2] } else { '' } }\n  $choices = switch ($previous) {\n")
	for _, key := range completionKeys(values) {
		fmt.Fprintf(&b, "    %s { %s; break }\n", quote("--"+key), array(values[key]))
		if key == "puzzle" {
			fmt.Fprintf(&b, "    '-p' { %s; break }\n", array(values[key]))
		}
	}
	b.WriteString("    default {\n      $command = if ($parts.Count -gt 1) { $parts[1] } else { '' }\n      switch ($command) {\n")
	for _, command := range completionCommands {
		fmt.Fprintf(&b, "        %s { %s; break }\n", quote(command), array(completionChoices(command)))
	}
	fmt.Fprintf(&b, "        default { %s }\n", array(completionChoices("")))
	b.WriteString("      }\n    }\n  }\n  $choices | Where-Object { $_.StartsWith($wordToComplete, [System.StringComparison]::OrdinalIgnoreCase) } | ForEach-Object {\n    [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)\n  }\n}\n")
	return b.String()
}
